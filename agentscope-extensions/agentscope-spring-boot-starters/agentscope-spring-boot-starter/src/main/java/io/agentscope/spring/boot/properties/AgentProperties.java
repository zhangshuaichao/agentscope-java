package io.agentscope.spring.boot.properties;

/**
 * 默认 ReActAgent bean 的配置属性。
 *
 * <p>典型 {@code application.yml} 配置：
 *
 * <pre>{@code
 * agentscope:
 *   agent:
 *     enabled: true
 *     name: "Assistant"
 *     sys-prompt: "You are a helpful AI assistant."
 *     max-iters: 10
 * }</pre>
 */
public class AgentProperties {

    /** 是否创建默认 ReActAgent bean。 */
    private boolean enabled = true;

    /** 默认智能体名称。 */
    private String name = "Assistant";

    /** 智能体使用的默认系统提示词。 */
    private String sysPrompt = "You are a helpful AI assistant.";

    /** 单次请求的最大 ReAct 迭代次数。 */
    private int maxIters = 10;

    public boolean isEnabled() {
        return enabled;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSysPrompt() {
        return sysPrompt;
    }

    public void setSysPrompt(String sysPrompt) {
        this.sysPrompt = sysPrompt;
    }

    public int getMaxIters() {
        return maxIters;
    }

    public void setMaxIters(int maxIters) {
        this.maxIters = maxIters;
    }
}
